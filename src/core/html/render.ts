// HTML renderers for crawl, reverse and diff reports. Each returns one
// self-contained document (inline CSS + inline SVG, no scripts, no CDN).

import type { CrawlReport } from "../crawl/schema.js";
import type { DiffReport } from "../diff/schema.js";
import type { ReverseReport } from "../reverse/schema.js";
import { PALETTE, SEVERITY_COLORS, barChart, columnChart, donutChart, esc, pairedBars, type Datum } from "./svg.js";
import { grid, kpis, link, page, raw, section, table } from "./page.js";

const n0 = (v: number | null | undefined): string =>
  v === null || v === undefined ? "-" : Math.round(v).toLocaleString("en-US");
const pct = (v: number): string => `${Math.round(v * 100)}%`;
const path = (u: string): string => u.replace(/^https?:\/\/[^/]+/, "") || "/";
const SEVERITIES = ["high", "medium", "low"] as const;

function footer(kind: string, version: string, at: string): string {
  return `Generated by seo-rea ${version} (${kind}) at ${at}. Self-contained file: no scripts or external resources.`;
}

export function depthChart(hist: Array<{ depth: number; pages: number }>): string {
  return columnChart(
    "Pages by click depth from the home page",
    hist
      .toSorted((a, b) => a.depth - b.depth)
      .map((d) => ({ label: `depth ${d.depth}`, value: d.pages, color: d.depth > 3 ? "#f59e0b" : PALETTE[0] })),
  );
}

export function severityChart(
  issues: Array<{ severity: "high" | "medium" | "low" }>,
  title = "Issues by severity",
): string {
  return donutChart(
    title,
    SEVERITIES.map((s): Datum => ({
      label: s,
      value: issues.filter((i) => i.severity === s).length,
      color: SEVERITY_COLORS[s],
    })),
  );
}

/** Ranking position buckets over the sampled keywords. */
export function positionBuckets(positions: Array<number | null>): Datum[] {
  const buckets: Array<[string, number, number, string]> = [
    ["#1", 1, 1, "#16a34a"],
    ["#2–3", 2, 3, "#22c55e"],
    ["#4–10", 4, 10, "#2563eb"],
    ["#11–20", 11, 20, "#f59e0b"],
    ["#21–50", 21, 50, "#ea580c"],
    ["#51–100", 51, 100, "#dc2626"],
  ];
  return buckets.map(([label, lo, hi, color]) => ({
    label,
    value: positions.filter((p) => p !== null && p >= lo && p <= hi).length,
    color,
  }));
}

export function renderCrawlHtml(r: CrawlReport): string {
  const s = r.stats;
  const high = r.issues.filter((i) => i.severity === "high").length;
  const top = r.summary.toSorted(
    (a, b) => SEVERITIES.indexOf(a.severity) - SEVERITIES.indexOf(b.severity) || b.count - a.count,
  );
  const summary = [
    `${s.pagesCrawled} pages crawled (${s.indexable} indexable)${s.complete ? ", crawl complete" : `, ${s.queuedLeft} URLs still queued`}.`,
    `${r.issues.length} issues across ${r.summary.length} rules; ${high} high severity.`,
    top[0]
      ? `Biggest problem: ${top[0].title} (${top[0].count} pages, ${top[0].severity}). Fix: ${top[0].fix}`
      : "No issues found.",
    `Deepest pages sit ${Math.max(0, ...r.graph.depthHistogram.map((d) => d.depth))} clicks from the start page.`,
  ];
  const body =
    kpis([
      { label: "Pages crawled", value: s.pagesCrawled },
      { label: "Indexable", value: s.indexable },
      { label: "Issues", value: r.issues.length, hint: `${high} high` },
      { label: "Rules triggered", value: r.summary.length },
      { label: "Sitemap URLs", value: s.sitemapUrls },
      { label: "Blocked by robots", value: s.blockedByRobots },
    ]) +
    section("Executive summary", `<ul class="summary">${summary.map((x) => `<li>${esc(x)}</li>`).join("")}</ul>`) +
    section(
      "Issues",
      grid(
        severityChart(r.issues),
        barChart(
          "Issues by rule",
          top.slice(0, 12).map((x) => ({ label: x.title, value: x.count, color: SEVERITY_COLORS[x.severity] })),
          { labelWidth: 230 },
        ),
      ) +
        table(
          ["Rule", "Severity", "Pages", "Fix"],
          top.map((x) => [x.title, x.severity, x.count, x.fix]),
          [2],
        ),
    ) +
    section(
      "Site structure",
      grid(
        depthChart(r.graph.depthHistogram),
        barChart(
          "Most internally linked pages",
          r.graph.inlinks.slice(0, 10).map((x) => ({ label: path(x.url), value: x.count })),
          { labelWidth: 230 },
        ),
      ),
    );
  return page(
    `Crawl: ${r.domain}`,
    `Run ${r.runId} · ${r.timestamps.finished}`,
    body,
    footer("crawl", r.toolVersion, r.timestamps.finished),
  );
}

export function renderReverseHtml(r: ReverseReport, crawl: CrawlReport | null = null): string {
  const rk = r.rankings ?? null;
  const k: Parameters<typeof kpis>[0] = [
    { label: "Pages crawled", value: r.coverage.pagesCrawled, hint: `${r.coverage.indexablePages} indexable` },
  ];
  if (rk) {
    k.push(
      { label: "Ranked keywords", value: n0(rk.totals.rankedKeywords), hint: `${rk.totals.sampled} sampled` },
      { label: "Top 10", value: n0(rk.totals.top10), hint: `${n0(rk.totals.top3)} in top 3` },
      { label: "Est. visits / month", value: n0(rk.totals.estTrafficMonthly) },
      {
        label: "Data cost",
        value: `$${rk.cost.actualUsd.toFixed(4)}`,
        hint:
          rk.cost.calls === 0 && rk.cost.fromCache > 0
            ? `${rk.cost.fromCache} response(s) from cache; original spend in the ledger`
            : `est. $${rk.cost.estimateUsd.toFixed(4)}; ${rk.cost.fromCache} cached`,
      },
    );
  }
  k.push({ label: "Tranco rank", value: n0(r.offpage.trancoRank) });
  let body =
    kpis(k) +
    section(
      "Executive summary",
      `<ul class="summary">${r.summary
        .map((f) => `<li><span class="tag">${esc(f.basis)} · ${esc(f.confidence)}</span>${esc(f.claim)}</li>`)
        .join("")}</ul>`,
    );
  if (rk) {
    const opp = rk.keywords
      .filter((x) => x.position !== null && x.position >= 4 && x.position <= 20 && (x.volume ?? 0) >= 100)
      .toSorted((a, b) => (b.volume ?? 0) - (a.volume ?? 0));
    body +=
      section(
        "Rankings",
        grid(
          columnChart(
            `Ranking position distribution (top ${rk.totals.sampled} keywords by traffic)`,
            positionBuckets(rk.keywords.map((x) => x.position)),
          ),
          barChart(
            "Estimated traffic by section",
            rk.sections
              .slice(0, 10)
              .map((x) => ({ label: x.key, value: x.etv, note: `${n0(x.etv)} (${pct(x.share)})` })),
          ),
          barChart(
            "Top keywords by estimated traffic",
            rk.keywords
              .slice(0, 12)
              .map((x) => ({ label: x.keyword, value: x.etv, note: `${n0(x.etv)} · #${x.position ?? "-"}` })),
            { labelWidth: 230, color: PALETTE[1] },
          ),
          donutChart(
            "Search intent mix (sampled keywords)",
            rk.intents.map((x) => ({ label: x.intent, value: x.keywords })),
          ),
        ),
      ) +
      section(
        "Competitor overlap",
        barChart(
          "Keywords shared with competitors",
          rk.competitors.slice(0, 12).map((x) => ({
            label: x.domain,
            value: x.sharedKeywords,
            note: `${n0(x.sharedKeywords)} · avg #${x.avgPosition?.toFixed(1) ?? "-"}`,
          })),
          { labelWidth: 200, color: PALETTE[4] },
        ) +
          table(
            ["Competitor", "Shared keywords", "Avg position", "Ranked keywords", "Est. traffic"],
            rk.competitors.map((x) => [
              x.domain,
              n0(x.sharedKeywords),
              x.avgPosition?.toFixed(1) ?? "-",
              n0(x.rankedKeywords),
              n0(x.estTrafficMonthly),
            ]),
            [1, 2, 3, 4],
          ),
      ) +
      section(
        "Page-two and near-miss opportunities (#4–20, 100+ searches)",
        table(
          ["Keyword", "Position", "Volume", "Est. traffic", "URL"],
          opp.slice(0, 20).map((x) => [x.keyword, x.position, n0(x.volume), n0(x.etv), link(x.url)]),
          [1, 2, 3],
        ),
      ) +
      section(
        "Top keywords",
        table(
          ["Keyword", "Position", "Volume", "Est. traffic", "Intent", "URL"],
          rk.keywords.slice(0, 25).map((x) => [x.keyword, x.position, n0(x.volume), n0(x.etv), x.intent, link(x.url)]),
          [1, 2, 3],
        ),
      );
  }
  body += section(
    "Content and structure",
    grid(
      barChart(
        "Pages by section",
        r.clusters.slice(0, 10).map((c) => ({ label: c.key, value: c.pages, note: `${c.pages} · ${c.template}` })),
      ),
      donutChart(
        "Page templates",
        r.templates.map((t) => ({ label: t.type, value: t.pages })),
      ),
      depthChart(r.linking.depthHistogram),
      crawl
        ? severityChart(crawl.issues)
        : barChart(
            "Schema types",
            r.schema.slice(0, 10).map((s) => ({ label: s.type, value: s.pages })),
          ),
    ) +
      (r.programmatic.length
        ? table(
            ["Programmatic pattern", "Pages", "Title pattern"],
            r.programmatic.map((p) => [raw(`<code>${esc(p.pattern)}</code>`), p.pages, p.titlePattern]),
            [1],
          )
        : ""),
  );
  body += section(
    "Playbook",
    table(
      ["Step", "Why", "Effort", "Impact"],
      r.playbook.map((p) => [p.step, p.why, p.effort, p.impact]),
    ),
  );
  if (r.unknowns.length)
    body += section("Unknowns", `<ul class="summary">${r.unknowns.map((u) => `<li>${esc(u)}</li>`).join("")}</ul>`);
  return page(
    `Reverse-engineering: ${r.domain}`,
    `Run ${r.runId} · ${r.timestamps.createdAt}${rk ? ` · rankings: ${rk.source}` : ""}`,
    body,
    footer("reverse", r.toolVersion, r.timestamps.writtenAt),
  );
}

export function renderDiffHtml(d: DiffReport): string {
  const c = d.counts;
  const statusColors: Record<string, string> = {
    fixed: "#16a34a",
    improved: "#22c55e",
    unchanged: "#94a3b8",
    "not-rechecked": "#cbd5e1",
    regressed: "#f59e0b",
    new: "#dc2626",
  };
  const status: Datum[] = [
    { label: "fixed", value: c.fixed },
    { label: "improved", value: c.improved },
    { label: "new", value: c.new },
    { label: "regressed", value: c.regressed },
    { label: "unchanged", value: c.unchanged },
    { label: "not-rechecked", value: c.notRechecked },
  ].map((x) => ({ ...x, color: statusColors[x.label] ?? PALETTE[9] }));
  const net = c.fixed + c.improved - c.new - c.regressed;
  const summary = [
    `${c.fixed} fixed and ${c.improved} improved vs ${c.new} new and ${c.regressed} regressed: net ${net >= 0 ? "+" : ""}${net}.`,
    ...d.metrics.slice(0, 4).map((m) => `${m.name}: ${m.old} → ${m.new} (${m.delta >= 0 ? "+" : ""}${m.delta}).`),
    ...d.notes,
  ];
  const deltas = d.ruleDeltas.filter((x) => x.delta !== 0).toSorted((a, b) => a.delta - b.delta);
  const body =
    kpis([
      { label: "Fixed", value: c.fixed },
      { label: "Improved", value: c.improved },
      { label: "New", value: c.new },
      { label: "Regressed", value: c.regressed },
      { label: "Unchanged", value: c.unchanged },
      { label: "Not rechecked", value: c.notRechecked },
    ]) +
    section("Executive summary", `<ul class="summary">${summary.map((x) => `<li>${esc(x)}</li>`).join("")}</ul>`) +
    section(
      "Trends",
      grid(
        donutChart("Findings by status", status),
        pairedBars(
          "Metrics before → after",
          d.metrics.map((m) => ({ label: m.name, before: m.old, after: m.new })),
        ),
        barChart(
          "Change in issue count by rule",
          deltas.slice(0, 14).map((x) => ({
            label: x.rule,
            value: x.delta,
            note: `${x.old} → ${x.new} (${x.delta > 0 ? "+" : ""}${x.delta})`,
            color: x.delta > 0 ? "#dc2626" : "#16a34a",
          })),
        ),
        severityChart(
          d.items.filter((i) => i.status === "new" || i.status === "regressed"),
          "New and regressed findings by severity",
        ),
      ),
    ) +
    section(
      "Changes",
      table(
        ["Status", "Severity", "Finding", "Detail", "URL"],
        d.items
          .filter((i) => i.status !== "unchanged")
          .slice(0, 200)
          .map((i) => [i.status, i.severity, i.title, i.detail, link(i.url)]),
      ),
    );
  return page(
    `Diff: ${d.domain}`,
    `${d.sourceKind} · ${d.old.runId} (${d.old.at}) → ${d.new.runId} (${d.new.at})`,
    body,
    footer("diff", d.toolVersion, d.new.at),
  );
}
